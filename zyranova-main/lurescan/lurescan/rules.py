def maps(
    sc: Sequence[str] = (),
    llm: Sequence[str] = (),
    web: Sequence[str] = (),
    ccm: Sequence[str] = (),
    attack: Sequence[str] = (),
    atlas: Sequence[str] = (),
    cwe: Sequence[str] = (),
    ssdf: Sequence[str] = (),
) -> Dict[str, Tuple[str, ...]]:
    raw = {
        "owasp-sc": sc,
        "owasp-llm": llm,
        "owasp-web": web,
        "csa-ccm": ccm,
        "attack": attack,
        "atlas": atlas,
        "cwe": cwe,
        "nist-ssdf": ssdf,
    }
    return {key: tuple(value) for key, value in raw.items() if value}


