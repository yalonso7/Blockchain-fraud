def catalog_mappings(rule: Rule) -> Dict[str, Tuple[str, ...]]:
    """Every framework item a rule can report, including pattern-specific ones."""
    return merge_mappings(rule.mappings, *rule.pattern_mappings)


def select_rules(include: Optional[Iterable[str]] = None, exclude: Optional[Iterable[str]] = None) -> List[Rule]:
    """Filter rules by id or id prefix (for example LS-SC or LS-AI-003)."""
    include = [item.strip().upper() for item in include or [] if item.strip()]
    exclude = [item.strip().upper() for item in exclude or [] if item.strip()]
    selected = []
    for rule in RULES:
        if include and not any(rule.id.startswith(prefix) for prefix in include):
            continue
        if any(rule.id.startswith(prefix) for prefix in exclude):
            continue
        selected.append(rule)
    return selected
